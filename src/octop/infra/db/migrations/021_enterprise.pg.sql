-- Company departments and managed employee assistants.
CREATE TABLE departments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL UNIQUE,
    created_at BIGINT NOT NULL
);
ALTER TABLE users ADD COLUMN department_id TEXT REFERENCES departments(department_id);
ALTER TABLE agents ADD COLUMN enterprise_kind TEXT NOT NULL DEFAULT 'legacy'
    CHECK (enterprise_kind IN ('legacy', 'personal', 'department', 'runtime'));
ALTER TABLE agents ADD COLUMN department_id TEXT REFERENCES departments(department_id);
ALTER TABLE agents ADD COLUMN definition_version INTEGER NOT NULL DEFAULT 1;
CREATE INDEX idx_users_department ON users(department_id);
CREATE INDEX idx_agents_department ON agents(department_id, enterprise_kind);
CREATE TABLE employee_assistants (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    agent_id TEXT UNIQUE REFERENCES agents(agent_id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    error TEXT
);
CREATE TABLE department_runtimes (
    definition_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    runtime_id TEXT NOT NULL UNIQUE REFERENCES agents(agent_id) ON DELETE CASCADE,
    definition_version INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY(definition_id, user_id)
);
