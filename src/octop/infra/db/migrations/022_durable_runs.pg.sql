-- Durable execution, approvals, write ledger and replayable events.
CREATE TABLE IF NOT EXISTS agent_runs (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id TEXT NOT NULL UNIQUE,
 agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
 thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE RESTRICT,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 version TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'queued' CHECK(state IN ('queued','running','waiting_approval','recovery_blocked','succeeded','failed','cancelled')),
 node TEXT, fence INTEGER NOT NULL DEFAULT 0,
 lease_until BIGINT NOT NULL DEFAULT 0,
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,
 request_json TEXT NOT NULL, result_json TEXT,
 next_seq BIGINT NOT NULL DEFAULT 0, terminal_seq BIGINT
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_run_active ON agent_runs(agent_id,thread_id)
 WHERE state IN ('queued','running','waiting_approval','recovery_blocked');
CREATE INDEX IF NOT EXISTS idx_run_thread ON agent_runs(thread_id,created_at);
CREATE TABLE IF NOT EXISTS run_events (
 run_id TEXT NOT NULL REFERENCES agent_runs(run_id) ON DELETE CASCADE,
 seq BIGINT NOT NULL, payload_json TEXT NOT NULL, created_at BIGINT NOT NULL,
 PRIMARY KEY(run_id,seq)
);
CREATE TABLE IF NOT EXISTS business_tools (
 name TEXT PRIMARY KEY, read_only INTEGER NOT NULL CHECK(read_only IN (0,1)),
 enabled INTEGER NOT NULL DEFAULT 1 CHECK(enabled IN (0,1)),
 revision INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS business_tool_grants (
 agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 tool_name TEXT NOT NULL REFERENCES business_tools(name),
 enabled INTEGER NOT NULL CHECK(enabled IN (0,1)), revision INTEGER NOT NULL DEFAULT 1,
 PRIMARY KEY(agent_id,user_id,tool_name)
);
CREATE TABLE IF NOT EXISTS run_approvals (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 approval_id TEXT NOT NULL UNIQUE,
 run_id TEXT NOT NULL REFERENCES agent_runs(run_id) ON DELETE CASCADE,
 call_id TEXT NOT NULL, tool_name TEXT NOT NULL,
 args_json TEXT NOT NULL, args_digest TEXT NOT NULL, policy_revision TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','approved','rejected','expired')),
 created_at BIGINT NOT NULL, decided_at BIGINT,
 UNIQUE(run_id,call_id)
);
CREATE TABLE IF NOT EXISTS tool_executions (
 run_id TEXT NOT NULL REFERENCES agent_runs(run_id) ON DELETE CASCADE,
 call_id TEXT NOT NULL, tool_name TEXT NOT NULL, args_digest TEXT NOT NULL,
 fence INTEGER NOT NULL, state TEXT NOT NULL CHECK(state IN ('started','succeeded','uncertain','not_executed')),
 result_json TEXT, resolution_note TEXT, resolved_by INTEGER REFERENCES users(id),
 PRIMARY KEY(run_id,call_id)
);
CREATE TABLE IF NOT EXISTS run_checkpoints (
 agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
 thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
 namespace TEXT NOT NULL, config_json TEXT NOT NULL,
 PRIMARY KEY(agent_id,thread_id,namespace)
);
CREATE TABLE IF NOT EXISTS run_checkpoint_entries (
 agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
 thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
 namespace TEXT NOT NULL, checkpoint_id TEXT NOT NULL,
 parent_id TEXT, checkpoint_type TEXT NOT NULL, checkpoint_data TEXT NOT NULL,
 metadata_type TEXT NOT NULL, metadata_data TEXT NOT NULL,
 created_at BIGINT NOT NULL,
 PRIMARY KEY(agent_id,thread_id,namespace,checkpoint_id)
);
CREATE TABLE IF NOT EXISTS run_checkpoint_writes (
 agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
 thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
 namespace TEXT NOT NULL, checkpoint_id TEXT NOT NULL,
 task_id TEXT NOT NULL, idx INTEGER NOT NULL, channel TEXT NOT NULL,
 value_type TEXT NOT NULL, value_data TEXT NOT NULL, task_path TEXT NOT NULL,
 PRIMARY KEY(agent_id,thread_id,namespace,checkpoint_id,task_id,idx)
);
